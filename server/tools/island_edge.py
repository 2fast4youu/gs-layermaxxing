#!/usr/bin/env python3
"""Generate (or --check) server/app/geometry/island_edge.json, the grid_version 7 edge contract (7.9.14).

Version 7 = version 6 (geometry/island_ground.json, unchanged) plus one rule: the friends' look-out (LIGHTHOUSE, every
stage: palm, look-out, signal station, lighthouse) is newly placed or moved only where its ground rectangle touches the
island's EDGE. Computed here independently of main.py (only from the two committed fixtures):

- meadow(land) = lattice cells of zone L (island_ground.json zones) inside the land stage's build ellipse
  (island_grid.json cells, the server's grid_buildable);
- outside = the non-meadow cells (and the ring of cells around the 0..20 lattice) connected to the lattice border by
  4-neighbour steps through non-meadow cells: beach, shore, rocks and water at the coast, never an inland rock;
- edge(land) = the meadow cells with a 4-neighbour in outside;
- spots[land][stage] = every spot on an EMPTY island where the look-out's whole ground (island_ground.json
  building:LIGHTHOUSE:<stage>) lies on the meadow and at least one of its cells is an edge cell.
The app reads nothing of this at run time (it computes the same rule, IslandGround.edge); its unit tests and
server/tests/test_v18_edge.py pin both implementations to this file.

Usage: python3 server/tools/island_edge.py [--check]   (standard library only)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GEO = ROOT / "server/app/geometry"
OUT = GEO / "island_edge.json"
GROUND = json.loads((GEO / "island_ground.json").read_text())
GRID = json.loads((ROOT / "server/app/island_grid.json").read_text())
N = 20


def zone(i, j):
    return GROUND["zones"][j][i] if 0 <= i <= N and 0 <= j <= N else "W"


def meadow(land):
    return {tuple(c) for c in GRID["cells"][str(land)] if zone(*c) == "L"}


def edge(land):
    m = meadow(land)
    outside, todo = set(), [(i, j) for i in range(-1, N + 2) for j in range(-1, N + 2) if i in (-1, N + 1) or j in (-1, N + 1)]
    while todo:
        c = todo.pop()
        if c in outside or c in m or not (-1 <= c[0] <= N + 1 and -1 <= c[1] <= N + 1):
            continue
        outside.add(c)
        todo += [(c[0] + 1, c[1]), (c[0] - 1, c[1]), (c[0], c[1] + 1), (c[0], c[1] - 1)]
    return {c for c in m if any((c[0] + dx, c[1] + dy) in outside for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))}


def spots(land, stage):
    r = GROUND["pieces"]["building:LIGHTHOUSE:%d" % stage]["lands"][land]["ground"]
    m, e = meadow(land), edge(land)
    out = []
    for j in range(N + 1):
        for i in range(N + 1):
            cells = {(i + x, j + y) for x in range(r[0], r[2] + 1) for y in range(r[1], r[3] + 1)}
            if cells <= m and cells & e:
                out.append([i, j])
    return out


def generate():
    return {
        "version": 7,
        "comment": "grid_version 7 edge contract, generated by server/tools/island_edge.py (do not edit by hand). "
                   "edge[land] = meadow cells (zone L inside the build ellipse) next to the coast (non-meadow connected to "
                   "the lattice border); lighthouse_spots[land][stage] = spots of the friends' look-out on an empty island "
                   "whose ground lies on the meadow and touches the edge. island_ground.json (version 6) is unchanged.",
        "buildings": ["LIGHTHOUSE"],
        "edge": {str(land): sorted([list(c) for c in edge(land)], key=lambda c: (c[1], c[0])) for land in range(6)},
        "lighthouse_spots": {str(land): {str(s): spots(land, s) for s in range(4)} for land in range(6)},
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = json.dumps(generate(), ensure_ascii=False, separators=(",", ":"), sort_keys=True) + "\n"
    if args.check:
        same = OUT.exists() and json.loads(OUT.read_text()) == json.loads(text)
        print("island_edge.json up to date" if same else "island_edge.json differs")
        return 0 if same else 1
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
